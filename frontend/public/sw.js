// Minimal real service worker backing lib/pushNotifications.ts - only
// handles the two events Web Push actually needs (`push` to show a
// notification, `notificationclick` to focus/open the dashboard). No
// offline caching, no asset interception: this is a push-only worker, not
// a PWA shell.

self.addEventListener("push", (event) => {
  let data = {};
  try {
    data = event.data ? event.data.json() : {};
  } catch {
    data = { body: event.data ? event.data.text() : "" };
  }

  event.waitUntil(
    self.registration.showNotification(data.title || "CanisterHub", {
      body: data.body || "",
      icon: "/vite.svg",
      data: { url: data.url || "/" },
    })
  );
});

self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const url = event.notification.data?.url || "/";
  event.waitUntil(
    clients.matchAll({ type: "window", includeUncontrolled: true }).then((windowClients) => {
      for (const client of windowClients) {
        if (client.url === url && "focus" in client) return client.focus();
      }
      if (clients.openWindow) return clients.openWindow(url);
    })
  );
});
