//! Shared module-level ACL types and generated Candid endpoints.

use candid::{CandidType, Principal};
use serde::{Deserialize, Serialize};

#[cfg(any(feature = "client", feature = "ic"))]
use crate::transport::{encode, flatten, CanisterClient};
#[cfg(any(feature = "client", feature = "ic"))]
use crate::Result as SdkResult;
#[cfg(feature = "client")]
use ic_agent::Agent;
#[cfg(feature = "client")]
use std::sync::Arc;

#[derive(Clone, Copy, Debug, Default, CandidType, Serialize, Deserialize, PartialEq, Eq)]
pub enum Access {
    #[default]
    None,
    Read,
    Write,
    Admin,
}

impl Access {
    pub const fn can_read(self) -> bool {
        matches!(self, Self::Read | Self::Write | Self::Admin)
    }

    pub const fn can_write(self) -> bool {
        matches!(self, Self::Write | Self::Admin)
    }

    pub const fn can_admin(self) -> bool {
        matches!(self, Self::Admin)
    }
}

#[derive(Clone, Debug, CandidType, Serialize, Deserialize, PartialEq, Eq)]
pub struct PermissionEntry {
    pub module: String,
    pub principal: Principal,
    pub access: Access,
}

/// Storage contract implemented by each package. This keeps the SDK from
/// claiming stable-memory ids that may already belong to the host canister.
pub trait PermissionStore {
    fn get(module: &str, principal: &Principal) -> Option<Access>;
    fn set(entry: PermissionEntry) -> std::result::Result<(), String>;
    fn remove(module: &str, principal: &Principal) -> std::result::Result<(), String>;
    fn list(module: Option<&str>) -> Vec<PermissionEntry>;
}

/// Client for the Candid methods generated by [`permission_api!`].
#[cfg(any(feature = "client", feature = "ic"))]
#[derive(Clone)]
pub struct PermissionClient(CanisterClient);

#[cfg(any(feature = "client", feature = "ic"))]
impl PermissionClient {
    #[cfg(feature = "client")]
    pub fn new(agent: Arc<Agent>, canister_id: Principal) -> Self {
        Self(CanisterClient::new(agent, canister_id))
    }

    #[cfg(feature = "client")]
    pub fn from_text(agent: Arc<Agent>, canister_id: &str) -> SdkResult<Self> {
        Ok(Self(CanisterClient::from_text(agent, canister_id)?))
    }

    #[cfg(feature = "ic")]
    pub fn for_canister(canister_id: Principal) -> Self {
        Self(CanisterClient::for_canister(canister_id))
    }

    pub async fn get(
        &self,
        module: impl Into<String>,
        principal: Principal,
    ) -> SdkResult<Option<Access>> {
        const METHOD: &str = "get_permission";
        self.0
            .query(METHOD, encode(METHOD, (module.into(), principal))?)
            .await
    }

    pub async fn list(&self, module: Option<String>) -> SdkResult<Vec<PermissionEntry>> {
        const METHOD: &str = "list_permissions";
        self.0.query(METHOD, encode(METHOD, (module,))?).await
    }

    pub async fn set(&self, entry: PermissionEntry) -> SdkResult<()> {
        const METHOD: &str = "set_permission";
        let result = self.0.update(METHOD, encode(METHOD, (entry,))?).await?;
        flatten(METHOD, result)
    }

    pub async fn remove(&self, module: impl Into<String>, principal: Principal) -> SdkResult<()> {
        const METHOD: &str = "remove_permission";
        let result = self
            .0
            .update(METHOD, encode(METHOD, (module.into(), principal))?)
            .await?;
        flatten(METHOD, result)
    }
}

pub fn validate_module(module: &str) -> std::result::Result<(), String> {
    if module.is_empty() {
        return Err("permission module must not be empty".to_string());
    }
    if module.len() > 128 {
        return Err("permission module must not exceed 128 bytes".to_string());
    }
    if !module
        .bytes()
        .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'-' | b'_' | b'.' | b'/'))
    {
        return Err(
            "permission module may contain only ASCII letters, digits, '-', '_', '.', and '/'"
                .to_string(),
        );
    }
    Ok(())
}

/// Generates a conventional Candid ACL API backed by a package-defined
/// [`PermissionStore`]. Read endpoints are public; mutations are restricted
/// to canister controllers and validate module names before touching storage.
///
/// ```ignore
/// canister_hub_sdk::permission_api!(crate::acl::Store);
/// ```
#[macro_export]
macro_rules! permission_api {
    ($store:ty) => {
        type CanisterHubPermissionAccess = $crate::permissions::Access;
        type CanisterHubPermissionEntry = $crate::permissions::PermissionEntry;

        #[ic_cdk::query]
        fn get_permission(
            module: String,
            principal: candid::Principal,
        ) -> Option<CanisterHubPermissionAccess> {
            if $crate::permissions::validate_module(&module).is_err() {
                return None;
            }
            <$store as $crate::permissions::PermissionStore>::get(&module, &principal)
        }

        #[ic_cdk::query]
        fn list_permissions(module: Option<String>) -> Vec<CanisterHubPermissionEntry> {
            if module
                .as_deref()
                .is_some_and(|name| $crate::permissions::validate_module(name).is_err())
            {
                return Vec::new();
            }
            <$store as $crate::permissions::PermissionStore>::list(module.as_deref())
        }

        #[ic_cdk::update]
        fn set_permission(entry: CanisterHubPermissionEntry) -> Result<(), String> {
            if !ic_cdk::api::is_controller(&ic_cdk::api::msg_caller()) {
                return Err("only a controller may change permissions".to_string());
            }
            $crate::permissions::validate_module(&entry.module)?;
            <$store as $crate::permissions::PermissionStore>::set(entry)
        }

        #[ic_cdk::update]
        fn remove_permission(module: String, principal: candid::Principal) -> Result<(), String> {
            if !ic_cdk::api::is_controller(&ic_cdk::api::msg_caller()) {
                return Err("only a controller may change permissions".to_string());
            }
            $crate::permissions::validate_module(&module)?;
            <$store as $crate::permissions::PermissionStore>::remove(&module, &principal)
        }
    };
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn write_implies_read_but_not_admin() {
        assert!(Access::Write.can_read());
        assert!(Access::Write.can_write());
        assert!(!Access::Write.can_admin());
    }

    #[test]
    fn validates_module_names() {
        assert!(validate_module("orders/write").is_ok());
        assert!(validate_module("").is_err());
        assert!(validate_module("orders write").is_err());
    }
}
