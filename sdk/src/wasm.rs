fn js_error(error: impl std::fmt::Display) -> JsValue {
    JsValue::from_str(&error.to_string())
}

fn from_js<T: DeserializeOwned>(value: JsValue) -> Result<T, JsValue> {
    serde_wasm_bindgen::from_value(value).map_err(js_error)
}

fn to_js<T: Serialize>(value: &T) -> Result<JsValue, JsValue> {
    let serializer = Serializer::new()
        .serialize_maps_as_objects(true)
        .serialize_large_number_types_as_bigints(true);
    value.serialize(&serializer).map_err(js_error)
}

fn string_patch(value: JsValue, field: &str) -> Result<Option<Option<String>>, JsValue> {
    if value.is_undefined() {
        Ok(None)
    } else if value.is_null() {
        Ok(Some(None))
    } else {
        value
            .as_string()
            .map(|value| Some(Some(value)))
            .ok_or_else(|| js_error(format!("{field} must be a string, null, or undefined")))
    }
}

async fn anonymous_agent(host: String, fetch_root_key: bool) -> Result<Arc<Agent>, JsValue> {
    let agent = Agent::builder().with_url(host).build().map_err(js_error)?;
    if fetch_root_key {
        agent.fetch_root_key().await.map_err(js_error)?;
    }
    Ok(Arc::new(agent))
}

fn access_from_string(access: &str) -> Result<Access, JsValue> {
    match access {
        "none" => Ok(Access::None),
        "read" => Ok(Access::Read),
        "write" => Ok(Access::Write),
        "admin" => Ok(Access::Admin),
        _ => Err(js_error("access must be one of: none, read, write, admin")),
    }
}

/// Browser/Wasm client for the API generated by `permission_api!`.
#[wasm_bindgen(js_name = PermissionClient)]
pub struct WasmPermissionClient {
    inner: PermissionClient,
}

#[wasm_bindgen(js_class = PermissionClient)]
impl WasmPermissionClient {
    #[wasm_bindgen(js_name = create)]
    pub async fn create(
        host: String,
        canister_id: String,
        fetch_root_key: bool,
    ) -> Result<WasmPermissionClient, JsValue> {
        let agent = anonymous_agent(host, fetch_root_key).await?;
        let inner = PermissionClient::from_text(agent, &canister_id).map_err(js_error)?;
        Ok(Self { inner })
    }

    pub async fn get(&self, module: String, principal: String) -> Result<JsValue, JsValue> {
        let principal = candid::Principal::from_text(principal).map_err(js_error)?;
        to_js(&self.inner.get(module, principal).await.map_err(js_error)?)
    }

    pub async fn list(&self, module: Option<String>) -> Result<JsValue, JsValue> {
        to_js(&self.inner.list(module).await.map_err(js_error)?)
    }

    pub async fn set(
        &self,
        module: String,
        principal: String,
        access: String,
    ) -> Result<(), JsValue> {
        self.inner
            .set(PermissionEntry {
                module,
                principal: candid::Principal::from_text(principal).map_err(js_error)?,
                access: access_from_string(&access)?,
            })
            .await
            .map_err(js_error)
    }

    pub async fn remove(&self, module: String, principal: String) -> Result<(), JsValue> {
        let principal = candid::Principal::from_text(principal).map_err(js_error)?;
        self.inner.remove(module, principal).await.map_err(js_error)
    }
}

